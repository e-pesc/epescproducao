CREATE FUNCTION public.update_updated_at_column() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$;
CREATE TRIGGER update_app_users_updated_at BEFORE UPDATE ON public.app_users FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
CREATE TRIGGER update_peixarias_updated_at BEFORE UPDATE ON public.peixarias FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
CREATE TRIGGER set_updated_at_clientes BEFORE UPDATE ON public.clientes FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
CREATE TRIGGER set_updated_at_fornecedores BEFORE UPDATE ON public.fornecedores FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
CREATE TRIGGER set_updated_at_produtos BEFORE UPDATE ON public.produtos FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

CREATE FUNCTION public.deduct_stock_on_sale_item() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  UPDATE public.produtos SET estoque_kg = estoque_kg - NEW.kg WHERE id = NEW.produto_id;
  RETURN NEW;
END;
$$;
CREATE TRIGGER deduct_stock_on_sale_item AFTER INSERT ON public.itens_venda FOR EACH ROW EXECUTE FUNCTION public.deduct_stock_on_sale_item();
CREATE FUNCTION public.deduct_stock_on_order_fulfill() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF OLD.status = 'pendente' AND NEW.status = 'atendido' THEN
    UPDATE public.produtos p SET estoque_kg = p.estoque_kg - ip.kg
    FROM public.itens_pedido ip WHERE ip.pedido_id = NEW.id AND p.id = ip.produto_id;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_deduct_stock_order_fulfill AFTER UPDATE ON public.pedidos FOR EACH ROW EXECUTE FUNCTION public.deduct_stock_on_order_fulfill();
