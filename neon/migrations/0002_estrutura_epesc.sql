-- Schema-only copy of the operational E-Pesc tables. No Lovable Cloud data or auth records are migrated.
-- Neon has no auth.users: auth_user_id and vendedor_id remain external identity UUIDs, without a foreign key.
-- Roles are held separately from app_users to prevent profile updates from granting privileges.
CREATE TYPE public.app_role AS ENUM ('vendedor', 'administrador', 'root');
CREATE TYPE public.produto_tipo AS ENUM ('inteiro', 'tratado');
CREATE TYPE public.movimento_tipo AS ENUM ('perda', 'quebra', 'outros', 'processamento', 'venda');
CREATE TYPE public.pedido_status AS ENUM ('pendente', 'atendido');
CREATE TYPE public.pagamento_tipo AS ENUM ('avista', 'prazo');
CREATE TYPE public.prepaid_method AS ENUM ('pix', 'cartao', 'dinheiro');

CREATE TABLE public.peixarias (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  razao_social text NOT NULL,
  cpf_cnpj text NOT NULL DEFAULT '',
  proprietario text NOT NULL DEFAULT '',
  whatsapp text NOT NULL DEFAULT '',
  endereco text NOT NULL DEFAULT '',
  cidade text NOT NULL DEFAULT '',
  dia_pagamento integer NOT NULL DEFAULT 10,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  mensalidade numeric NOT NULL DEFAULT 0,
  vendedor_root_id uuid,
  plano_gratuito boolean NOT NULL DEFAULT false,
  desconto_mensalidade numeric NOT NULL DEFAULT 0,
  desconto_mes_referencia text
);
CREATE TABLE public.app_users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_user_id uuid,
  name text NOT NULL,
  cpf text NOT NULL DEFAULT '',
  whatsapp text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  peixaria_id uuid REFERENCES public.peixarias(id) ON DELETE CASCADE
);
CREATE TABLE public.user_roles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
  role public.app_role NOT NULL,
  UNIQUE (user_id, role)
);
ALTER TABLE public.peixarias ADD CONSTRAINT peixarias_vendedor_root_id_fkey FOREIGN KEY (vendedor_root_id) REFERENCES public.app_users(id) ON DELETE SET NULL;

